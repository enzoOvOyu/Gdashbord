let lang = "zh";
try {
  const saved = localStorage.getItem(STORE_KEY);
  if (saved === "zh" || saved === "en") lang = saved;
} catch (e) { /* ignore */ }

export function getLang() {
  return lang;
}

export function setLang(l) {
  lang = l === "en" ? "en" : "zh";
  try { localStorage.setItem(STORE_KEY, lang); } catch (e) { /* ignore */ }
  return lang;
}

export function toggleLang() {
  return setLang(lang === "zh" ? "en" : "zh");
}

// 取 UI 文案
export function t(key, fallback) {
  const d = STR[lang] || STR.zh;
  if (d[key] != null) return d[key];
  if (STR.zh[key] != null) return STR.zh[key];
  return fallback != null ? fallback : key;
}

// L(value)：
//  1) { zh, en } 双语对象 → 按当前语言取值
//  2) i18n key（如 "ov.title"）→ 走 t() 取文案（页面与组件可直接传 key）
//  3) 普通字符串 / 数字 → 原样返回
export function L(value) {
  const v = value;
  if (v == null) return "";
  if (typeof v === "string" || typeof v === "number") {
    const s = String(v);
    if (STR.zh[s] != null) return t(s);
    return s;
  }
  return pick(v, lang);
}

// 状态标签：状态机值 → 双语文案
const STATUS_KEYS = ["running", "stopped", "starting", "error", "healthy", "scaled-zero", "completed", "queued", "failed", "warning", "success", "info", "pending", "provisioning", "terminating", "active", "suspended", "invited", "resolved", "open", "degraded", "maintenance"];
export function statusText(st) {
  if (STATUS_KEYS.includes(st)) return t("status." + st);
  return L(st);
}

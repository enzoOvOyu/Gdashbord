function pick(o, lang) {
  if (o == null) return "";
  if (typeof o === "string" || typeof o === "number") {
    const s = String(o);
    if (STR.zh && STR.zh[s] != null) return (STR[lang] || STR.zh)[s] != null ? (STR[lang] || STR.zh)[s] : STR.zh[s];
    return s;
  }
  if (Array.isArray(o)) return o.map((x) => pick(x, lang)).join(" / ");
  return o[lang] != null ? o[lang] : o.zh != null ? o.zh : JSON.stringify(o);
}

